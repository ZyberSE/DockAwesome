"""Generate the antialiased About glyph atlas.

Usage: python3 tools/make-about-font.py VeraSans.ttf VeraSansBold.ttf

Writes src/about_font.c. Opening Vera Sans through diskfont takes about 11 s
on Vampire after a reboot, so About draws prerendered glyphs instead. Each
style keeps the line height the diskfont size gave (20, 12, 11 and 13 px).
The data is a rendering of Bitstream Vera Sans (Copyright (c) 2003 by
Bitstream, Inc.); the font files themselves are not part of DockAwesome.
Requires Pillow.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

REGULAR, BOLD = sys.argv[1:3]
# Order matches enum AboutStyle in include/about_font.h.
STYLES = (("title", BOLD, 20), ("body", REGULAR, 12), ("small", REGULAR, 11), ("name", REGULAR, 13))
FIRST, LAST = 32, 126


def fitted(path, line_height):
    """The largest em size whose ascent plus descent fits the line height."""
    size = line_height
    while size > 4:
        font = ImageFont.truetype(path, size)
        ascent, descent = font.getmetrics()
        if ascent + descent <= line_height:
            return font, ascent
        size -= 1
    raise SystemExit(f"{path} does not fit {line_height} px")


def style_data(name, path, line_height):
    font, ascent = fitted(path, line_height)
    glyphs, coverage = [], bytearray()
    for code in range(FIRST, LAST + 1):
        char = chr(code)
        left, _, right, _ = font.getbbox(char)
        width = max(0, right - left)
        advance = round(font.getlength(char))
        offset = len(coverage)
        if width:
            cell = Image.new("L", (width, line_height), 0)
            ImageDraw.Draw(cell).text((-left, 0), char, font=font, fill=255)
            coverage += cell.tobytes()
        glyphs.append((left, width, advance, offset))
    return {"name": name, "height": line_height, "baseline": ascent,
            "glyphs": glyphs, "coverage": bytes(coverage)}


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return "\n".join(rows)


def main():
    styles = [style_data(*style) for style in STYLES]
    out = ["/* Generated by tools/make-about-font.py from Bitstream Vera Sans.",
           "   Copyright (c) 2003 by Bitstream, Inc. Do not edit. */",
           '#include "about_font.h"', ""]
    for s in styles:
        out.append(f"static const unsigned char {s['name']}_coverage[] = {{")
        out.append(c_bytes(s["coverage"]) or "    0,")
        out.append("};")
        out.append(f"static const AboutGlyph {s['name']}_glyphs[] = {{")
        for left, width, advance, offset in s["glyphs"]:
            out.append(f"    {{{left},{width},{advance},{offset}}},")
        out.append("};")
    out.append("const AboutFace about_font[ABOUT_STYLES] = {")
    for s in styles:
        out.append(f"    {{{s['height']},{s['baseline']},{s['name']}_glyphs,{s['name']}_coverage}},")
    out.append("};")
    target = Path(__file__).resolve().parents[1] / "src" / "about_font.c"
    target.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"{target}: " + ", ".join(f"{s['name']} {len(s['coverage'])} bytes" for s in styles))


if __name__ == "__main__":
    main()
